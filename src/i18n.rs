/// Translate `key` for locale `lang` (`"en"` | `"vi"` | `"zh-CN"` | `"ja"`).
///
/// Callsite keys are string literals, so `key` is `&'static str` and a miss
/// can return it directly — no allocation, no leak. Falls back to English
/// when the key exists but the locale is unknown.
pub fn tr(key: &'static str, lang: &str) -> &'static str {
    for &(k, en, vi, zh, ja) in STRINGS {
        if k == key {
            return match lang {
                "vi" => vi,
                "zh-CN" => zh,
                "ja" => ja,
                _ => en,
            };
        }
    }
    key
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_has_all_languages() {
        for &(key, en, vi, zh, ja) in STRINGS {
            for (lang, value) in [("en", en), ("vi", vi), ("zh-CN", zh), ("ja", ja)] {
                assert!(!value.is_empty(), "empty value for {key} in {lang}");
                assert_eq!(tr(key, lang), value, "wrong value for {key} in {lang}");
            }
        }
    }

    #[test]
    fn unknown_language_falls_back_to_english() {
        for &(key, en, ..) in STRINGS {
            assert_eq!(tr(key, "fr"), en);
            assert_eq!(tr(key, ""), en);
        }
    }

    #[test]
    fn unknown_key_returns_key() {
        assert_eq!(tr("no.such.key", "en"), "no.such.key");
        assert_eq!(tr("no.such.key", "vi"), "no.such.key");
    }
    /// Every string of the rebuilt Appearance page and its shared units must
    /// be present in all four locales and must not silently fall back to the
    /// key name (the plan's R8 acceptance). Prefixes: `appearance.*` for the
    /// page, `unit.*` for the reusable unit words.
    #[test]
    fn appearance_keys_are_translated_in_every_locale() {
        let mut counted = 0;
        for &(key, en, vi, zh, ja) in STRINGS {
            if !(key.starts_with("appearance.") || key.starts_with("unit.")) {
                continue;
            }
            counted += 1;
            for (lang, value) in [("en", en), ("vi", vi), ("zh-CN", zh), ("ja", ja)] {
                assert!(
                    !value.trim().is_empty(),
                    "empty appearance string for {key} in {lang}"
                );
                assert_ne!(value, key, "{key} falls back to the key name in {lang}");
            }
        }
        assert!(
            counted >= 160,
            "expected the rebuilt Appearance page's string set, found {counted}"
        );
    }
}
